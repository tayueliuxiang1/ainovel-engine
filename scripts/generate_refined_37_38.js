“西市乃整个大唐帝国乃至四海诸国的货物集散心脏！每天进出西市的皮毛、药材、绸缎、马匹数以万计。单凭你聚顺和这一间百货杂铺，哪怕伙计们个个生出三头六臂，能辐射的不过方圆半条街的散客与小作坊。要想真正将苏氏坚皂打造成关陇第一日化巨擘，这一间铺子，远远不够！”

严掌柜浑身猛地一震，失声道：“小郎君的意思是……咱们再在西市买下一处临街大门面开分号？可这西市寸土寸金，一间像样的大铺子，没有五百贯上千贯现钱，根本拿不下来啊！”

“买铺子开分号，那是蠢人的做法。”

苏白冷笑一声，眼中闪烁着现代商业渠道整合的降维锋芒：

“天下熙熙皆为利来，西市最不缺的，就是那些手握海量客源、却同样为污垢磨损头疼的百年大行栈！咱们不需要花一文钱去买铺面，咱们要借鸡生蛋，让西市最大的巨头商栈，变成苏家坚皂的天然分销专柜！”

“借鸡生蛋？专柜分销？！”严掌柜听得满头雾水，但心中的震撼却无以复加。

半个时辰之后。

在严掌柜的亲自引荐下，苏白带着赵二叔，迈入了西市南区一座气势雄伟、极具异域风情的巨大砖石城堡建筑——大食客栈！

大食客栈乃是大唐境内数一数二的外藩商贸大本营，常年驻扎着数百名来自大食帝国与波斯高原的顶级巨贾豪商。

客栈最奢华的顶层穹顶雅厅内，波斯大掌柜米尔扎正裹着厚厚的纯白羊绒缠头，盘腿坐在厚实的名贵毛毯上，一边抽着水烟，一边对着几名管事愤怒地咆哮：

“真主降罪！一群没用的蠢货！这可是从波斯大不里士工坊耗时三年才织就的整整两百匹特级纯白双峰驼毛贡毡！运到大唐是为了献给朝廷亲王的大礼！你们竟然敢用廉价的关中草木灰水去清洗上面的骆驼油脂？！”

米尔扎气得浑身发抖，指着地上几匹被洗得发脆、毛结发硬、甚至原本鲜艳的金丝纹路严重褪色剥落的名贵驼毛毯，眼珠子都红了：

“毛质全硬了！金丝全暗了！这一匹地毯便值整整三十匹上等蜀锦！你们赔得起吗？！西市还有没有能洗净这等顽固油脂、却绝不伤及驼毛分毫的神物？！若是没有，本掌柜剥了你们的皮！”

几名胡人管事跪倒在地，瑟瑟发抖。

就在此时，雅厅门帘微动，苏白带着赵二叔阔步而入。

“大掌柜若是想救这批波斯极品驼毛毡，苏某手里恰好有解药。”苏白声音不大，却字字铿锵，瞬间在穹顶雅厅内清晰回荡。

米尔扎转过头，一双深凹的碧蓝眼眸带着傲慢与怀疑，冷冷打量着苏白：

“大唐的年轻匠人？哼，严掌柜方才对本掌柜百般吹嘘，说你造的去垢物天下无双。但你可知本掌柜这驼毛毯是何等娇贵？任何烈性碱水只要沾上，毛根必断！大唐那些贵妇所用的澡豆、胰子，香则香矣，却连羊油的一层浮沫都化不开！你凭什么大言不惭？！”

苏白神色淡然，甚至连半句多余的废话都懒得说。

他朝着赵二叔使了个眼色。

赵二叔跨前一步，从皮囊中取出一只规整的黄铜水盆，注入滚烫的开水；苏白则反手从袖中拔出一柄锋利的小刻刀，在随身携带的一块四两特大号重工坚皂上，极其细腻地削下了薄如蝉翼的二十片皂屑，投入滚水之中轻轻搅动。

刹那间，一股浓郁、温润且纯净的草木与油脂清香在大厅内弥漫开来。

“米尔扎大掌柜，请将受损最重、油脂最厚的一角驼毛毯浸入盆中。”苏白伸手虚引。

米尔扎冷哼一声，亲自抓起一匹沾满了黑臭老羊脂、板结硬如生铁的驼毛毯边角，狠狠按入了铜盆之中。

不可思议的奇迹，在所有大食波斯巨贾的眼皮底下，轰然上演！

只见那原本在草木灰水中纹丝不动的顽固老羊脂油，在接触到细腻乳白泡沫的瞬间，犹如坚冰坠入烈火，以肉眼可见的速度彻底崩解、乳化！

苏白伸出双手，不轻不重地在毛毯纤维间顺着毛流方向推揉了数十息，随后将毛毯捞出，在另一盆温清水中轻轻漂洗。

“啪！”

苏白将漂洗干净的毛毯角展开，在炭火盆旁轻轻一抖。

原本黑臭板结、硬如铁石的驼毛，不仅上面的陈年羊脂油被涤荡得荡然无存，那细密的驼毛纤维更在热气蒸腾下奇迹般地重新蓬松挺立起来！每一根绒毛都恢复了温润如玉的纯白光泽，上面的金丝绣线更是熠熠生辉、璀璨夺目，比刚刚织就出炉时还要鲜活高贵！

“真主安拉在上！”

米尔扎嘴里的水烟袋当啷一声跌落在名贵地毯上，整个人失魂落魄地扑倒在铜盆前，颤抖着伸出双手抚摸着那蓬松柔软的驼毛，发出了近乎疯魔般的惊呼：

“不可思议！这简直是真主赐予大地的神迹！没有断毛！没有褪色！油脂全消，绒毛蓬松如初生羔羊！大唐的神工……大唐的神工啊！”

雅厅内的数十名波斯豪商齐齐跪伏在地，目光狂热得犹如见到了活生生的神明！

米尔扎猛地转过身，一把抱住苏白的小腿，碧蓝的眼睛里满是狂热与贪婪：

“苏匠首！我的朋友！我的兄弟！这种神皂你有多少？大食客栈全要了！每块哪怕五十文、一百文，本掌柜照单全收！”

“米尔扎大掌柜，苏某不是来单卖肥皂的。”

苏白轻轻退后半步，从容不迫地从怀中取出两张早已起草好的契约文牒，按在米尔扎面前的矮几上，朗声道：

“苏氏坚皂，不接受任何一家商栈买断独占。苏某要在大食客栈正堂临街正门，设立‘苏氏坚皂特供专柜’！专供四两特大号重工坚皂，专销大食、波斯与西域各藩国清洗名贵毛毯与丝绢贡品！

工坊以每块十二文的底价给大食客栈足量供货；专柜对外统一明码标价每块十六文！大食客栈每卖出一块，净赚四文暴利！但大食客栈必须立下重誓：专柜所销之物，独此苏氏一家，永不掺伪！”

每块净赚四文！

大食客栈每天消耗与过往客商的需求何止数百块？！这几乎是一座凭空送上门来的金山！

“签！立刻签！真主作证，谁敢毁约，大食客栈剥了他的皮！”

米尔扎甚至连条款都没多看一眼，咬破食指，在文牒上重重按下了血红的手印，并加盖了波斯商会的纯金火漆大印！

拿下大食客栈！

随后，借着这场神迹洗毯的轰动效应，苏白雷霆出击，连战连捷！

在西市北区拥有三千匹骡马的陇右大车栈内，面对堆积如山、因马汗血水板结发臭的硬生牛皮马鞍与皮具，苏白用一两标准方砖现场试洗，片刻间让老旧硬皮恢复柔韧油亮！陇右大车栈大掌柜当场拍板，设立第二处专柜，兼销大号与一两标准方砖！

紧接着，专门垄断关中乃至陇西毛皮硝制贸易的西域毛皮行，见识到了半两去脂小块对生羊皮腥臭皮脂的恐怖化解力后，毫不犹豫签下契约，独家包销半两去脂小块，设立第三处专柜！

至此，加上原有的聚顺和老铺专柜，以及城东裴敏永泰丰的特供渠道——

四大专柜联营网络，犹如一张精密织就的商业天网，彻底将整个长安西市的毛皮、驼毯、马具、丝绢与市井百货，尽数笼罩在了苏白的掌心之中！

