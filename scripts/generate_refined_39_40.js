在大唐贞观初年，一文钱能买一个热胡饼，五百文能买一石精白米，十贯钱足够在长安城偏僻坊区买下一座规整的小四合院！

而这笔巨款，仅仅是他们这帮底层泥腿子工匠，在短短两个月里用一双双手拼出来的净利！

“好！算得清白！赚得堂堂正正！”

门槛旁的苏成海仰起头，将壶中滚烫的稠酒一饮而尽，狠狠一抹嘴角，曾经被军旅摧折的脊梁，在这一刻挺拔得犹如一杆不屈的长枪！

苏白放下账本，神色庄严肃穆。

“利钱算清了，接下来，论功分红！”

苏白伸出双手，径直伸向第一只木箱，端端正正抱出了整整两千枚用新麻绳串好的大钱——

两贯足钱！

沉甸甸的两贯铜钱被苏白双手托起，稳步走到了堂下的赵二叔面前。

“赵二叔！”苏白朗声道。

赵二叔猛地一颤，独臂有些局促地贴在裤腿上，粗糙的面庞涨得通红：“白哥儿……你这是作甚？二叔每个月跟着你管饭吃肉，身上穿着新皮袄，你给二叔发这老些钱作甚？！”

苏白神色无比凝重，双手将两贯大钱重重塞入赵二叔怀中：

“二叔！工坊初创，若无你挺身而出震慑宵小，水车机括早已被奸人暗算；更关键的是，南原神车防反转安全保险销、异形曲柄连杆的百炼精钢打制，全出自二叔二十年的铁匠绝艺！苏某此前立下规矩：工科绝活入股，享技术分红！这两贯足钱，是二叔应得的干股分红！请二叔堂堂正正收下！”

两贯大钱，整整十六斤沉！

赵二叔紧紧抱着怀里冰凉却滚烫的铜钱，整个人如遭雷击般僵立在原地。

这位在大唐天策府征战半生、断了一条手臂、流干了热血却被官府当成残废粗胚随意打发的老兵，在这一刻，眼眶里浑浊的泪水终于犹如决堤的洪水般汹涌而出！

“两贯钱……老子打了一辈子仗，流了一身血，受尽了世人的白眼与践踏……今天……今天老子手里的这门打铁手艺，竟然值整整两贯大钱了！”

赵二叔用粗糙的袖口狠狠抹着眼泪，哭得像个受尽委屈的孩子，又哭又笑地嘶吼道：

“白哥儿！好孩子！二叔这辈子……这条残命誓死跟着你干！”

满堂动容！

一个底层老匠人的尊严，在工科制度与真金白银的尊重面前，被高高立上了云端！

苏白眼眶微湿，用力拍了拍赵二叔的肩膀。

随后，苏白转身从第二只箱子里，捧出了一贯大钱外加五百枚散钱，放在了王木匠面前：

“王叔！起早贪黑修正水车大轮，带徒弟日夜刨制老槐木防伪燕尾号牌，居功至伟！这是一贯五百文，是你的骨干大功分红！”

王木匠噗通一声跪倒在地，捧着一贯半大钱嚎啕大哭：

“白哥儿！老木我这辈子做木工，都是给人当牛做马受尽苛扣！做梦都不敢想能拿这么多分红啊！以后白哥儿指东老木绝不往西，作坊就是我的命根子！”

“起来，王叔！手艺人凭本事吃饭，挺直腰杆站着拿钱！”苏白一把将王木匠搀扶起来。

接着，苏白转头看向马老三等六名帮工汉子：

“马老三，还有几位叔伯兄弟！你们白日里推车运料，夜里守棚巡查，忠心耿耿，从未有一丝懈怠！虽然月内已结清了你们每人八百文的足色工钱，但今晚是全坊大庆！工坊额外赏给你们每人整整两百文开春大红包！”

六封用红纸仔细包好的铜钱，共计一贯二百文，稳稳递到了六名汉子手中！

“两百文红包？！”

马老三捧着红包，激动得浑身发抖，带着几名汉子齐刷刷跪下，对着八仙桌砰砰砰连磕了三个响头：

“谢东家！谢白哥儿！小人全家给苏家效死力！永不背叛！”

分红支出清清楚楚：

赵二叔技术分红两贯（两千文）；

王木匠骨干分红一贯五百文（一千五百文）；

六名帮工开春红包一贯二百文（一千二百文）！

分红总计支出四贯七百文足钱！

至此，三只大箱子里的十一贯三百文净利润，扣除四贯七百文分红之后，八仙桌上依然稳稳当当端坐着整整六贯六百文沉甸甸的纯利现钱！

苏白转过身，将其中两只箱子合拢，推到了苏成海与陆氏面前：

“爹，娘！这剩下的六贯六百文纯利，儿子也做好了定数规划：

这两贯大钱，作为家里的用度，给爹买终南山最好的药酒温养筋骨旧伤，给娘裁几身绸缎衣裳！

这四贯大钱，作为工坊开春扩建的备用专银，用于建新工棚、采购精铁巨木！

最后的六百文散钱，作为工坊账房的常备流动金，以备不时之需！”

数字丝丝入扣，账目毫厘不差！

陆氏搂着两贯大钱，泣不成声；苏成海紧紧握着儿子的手，眼中满是无尽的骄傲与自豪！

就在此时，院门外忽然传来了阵阵压抑的低语声与脚步声。

原来是云阳庄的数十名本村乡邻与族老，听闻了苏家院子里的大动静，深夜纷纷披着棉袄聚拢在门外。透过敞开的柴门，乡邻们亲眼见到了八仙桌上那如山般金光闪闪的大铜钱，见到了赵二叔、王木匠和马老三怀里沉甸甸的巨款！

“老天爷啊……苏家当真发了泼天大财了！”

“赵瘸子拿了两贯钱分红！王木匠拿了一贯半！”

“连马老三那个打杂的都拿了足足一两百文红包啊！”

整个云阳庄在深夜中彻底轰动了！

无数曾经轻视苏家的族人眼珠子都红了，眼神中充满了无尽的艳羡、震撼与敬畏！

苏白深吸了一口气，迈着沉稳从容的步伐，走到了正堂门前。

“吱呀——”

厚重的正堂大木门被他一把推开！

初春清凉微暖的夜风拂面而来，吹动着少年坚毅的衣袍。

苏白迎着漫天璀璨的星斗，迎着门外数十名震撼敬畏的乡邻目光，昂首挺立，朗声向整个关中大地宣告：

“二月立春，水车大兴，坚皂出关！

苏家工坊，明日起正式在云阳庄招募第一批十名学徒工！

只要品行端正、踏实肯干，苏家管吃管住，授工科神术，同享工坊分红！

大唐关陇的这片天地，该轮到咱们手艺人挺直腰杆，翻天覆地了！”

“轰——！”

苏家小院内外，爆发出山崩海啸般的狂热欢呼之声！

老兵的泪水、家人的荣耀、手艺人的尊严与漫天璀璨的星辰交相辉映。

